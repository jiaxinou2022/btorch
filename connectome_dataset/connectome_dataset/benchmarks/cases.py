def _load_rsnn_defaults(graph: str) -> dict[str, Any]:
    if not graph.startswith("mice_column_v1") or not _MICE_RSNN_PARAMS.exists():
        return {}
    with open(_MICE_RSNN_PARAMS) as f:
        params = yaml.safe_load(f) or {}
    return {
        "timesteps": RSNN_DEFAULTS.timesteps,
        "batch_size": RSNN_DEFAULTS.batch_size,
        "num_input": params.get("input", {}).get("num_input_neuron", RSNN_DEFAULTS.num_input),
        "num_output": RSNN_DEFAULTS.num_output,
        "params": params,
    }


def load_rsnn_case(
    graph: str,
    replicate: int = 1,
    *,
    timesteps: int | None = None,
    batch_size: int | None = None,
    num_input: int | None = None,
    num_output: int | None = None,
    inter_density: float | None = None,
    replicate_seed: int = 0,
) -> RSNNCase:
    entry, matrix = _load_entry(graph, replicate, inter_density=inter_density, seed=replicate_seed)
    defaults = _load_rsnn_defaults(entry["name"])
    meta = _base_metadata(entry, matrix)
    if "params" in defaults:
        meta["rsnn_params"] = defaults["params"]
    case_id = f"{entry['name']}_rsnn"
    return RSNNCase(
        case_id=case_id,
        graph_id=entry["name"],
        replicate=replicate,
        matrix=matrix,
        n=entry["n_rows"],
        nnz=entry["nnz"],
        density=entry["density"],
        timesteps=timesteps or defaults.get("timesteps", RSNN_DEFAULTS.timesteps),
        batch_size=batch_size or defaults.get("batch_size", RSNN_DEFAULTS.batch_size),
        num_input=num_input or defaults.get("num_input", RSNN_DEFAULTS.num_input),
        num_output=num_output or defaults.get("num_output", RSNN_DEFAULTS.num_output),
        metadata=meta,
    )
